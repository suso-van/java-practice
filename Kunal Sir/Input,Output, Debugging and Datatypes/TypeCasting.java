public class TypeCasting {
    public static void main(String[] args) {
        int a = 10;
        float b = a; 
        System.out.println("Value of b: " + b);

        double c = 20.5;
        int d = (int) c;
        System.out.println("Value of d: " + d);

        byte e = 100;
        byte f =(byte) e;
        System.out.println("Value of f: " + f);
    }


}
